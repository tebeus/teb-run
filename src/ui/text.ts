export type Align = 'left' | 'center' | 'right';

const GLYPH_SIZE = 8;

function glyphFor(ch: string): readonly string[] {
  return GLYPHS[ch] ?? GLYPHS['?'];
}

/** Larghezza in pixel di una stringa disegnata a una data scala. Pura. */
export function measureText(text: string, scale: number): number {
  return text.length * GLYPH_SIZE * scale;
}

function drawGlyph(
  ctx: CanvasRenderingContext2D,
  glyph: readonly string[],
  x: number,
  y: number,
  scale: number,
): void {
  for (let row = 0; row < GLYPH_SIZE; row++) {
    const line = glyph[row];
    for (let col = 0; col < GLYPH_SIZE; col++) {
      if (line[col] === '#') ctx.fillRect(x + col * scale, y + row * scale, scale, scale);
    }
  }
}

/**
 * Disegna testo con il font bitmap, un fillRect per pixel acceso. I
 * caratteri non supportati (e le minuscole, mappate alle stesse maiuscole)
 * non lanciano mai: usano il glifo di fallback '?'. `align` sceglie l'ancora
 * orizzontale rispetto a `x`; `y` è sempre l'angolo superiore del testo.
 */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  scale: number,
  color: string,
  align: Align = 'left',
): void {
  if (text.length === 0) return;
  const w = measureText(text, scale);
  const startX = align === 'center' ? x - w / 2 : align === 'right' ? x - w : x;
  ctx.fillStyle = color;
  for (let i = 0; i < text.length; i++) {
    drawGlyph(ctx, glyphFor(text[i].toUpperCase()), startX + i * GLYPH_SIZE * scale, y, scale);
  }
}

/**
 * Testo con contorno scuro (spec §11). Due passate: prima gli stessi pixel
 * del font gonfiati di un pixel in ogni direzione, poi il testo pieno sopra.
 * Quattro copie spostate costerebbero cinque passate invece di due.
 */
export function drawTextOutlined(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  scale: number,
  color: string,
  align: Align = 'left',
  outline = '#101018',
): void {
  if (text.length === 0) return;
  const w = measureText(text, scale);
  const startX = align === 'center' ? x - w / 2 : align === 'right' ? x - w : x;
  ctx.fillStyle = outline;
  for (let i = 0; i < text.length; i++) {
    const glyph = glyphFor(text[i].toUpperCase());
    for (let row = 0; row < GLYPH_SIZE; row++) {
      const line = glyph[row];
      for (let col = 0; col < GLYPH_SIZE; col++) {
        if (line[col] !== '#') continue;
        ctx.fillRect(startX + i * GLYPH_SIZE * scale + col * scale - 1, y + row * scale - 1, scale + 2, scale + 2);
      }
    }
  }
  drawText(ctx, text, x, y, scale, color, align);
}
